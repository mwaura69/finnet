 const sell=(await request(app).post(`/api/portfolios/${p.id}/transactions`).set(auth).send({...base,type:'SELL',quantity:20,unitPrice:30,tradeDate:'2026-02-01'}).expect(201)).body.data;
 const summary=(await request(app).get(`/api/portfolios/${p.id}/summary`).set(auth).expect(200)).body.data;
 assert.equal(summary.holdings[0].netQuantity,80);assert.equal(summary.totalInvested,2000);assert.equal(summary.totalValue,2400);assert.equal(summary.realizedGain,100);
 await request(app).delete('/api/transactions/'+buy.id).set(auth).expect(422);
