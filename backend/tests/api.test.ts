 await request(app).get(`/api/portfolios/${p.id}/summary`).set('Authorization','Bearer '+other).expect(404);
 await request(app).put('/api/portfolios/'+p.id).set('Authorization','Bearer '+other).send(input).expect(404);
 await request(app).post(`/api/portfolios/${p.id}/transactions`).set('Authorization','Bearer '+other).send(base).expect(404);
 await request(app).delete('/api/portfolios/'+p.id).set('Authorization','Bearer '+other).expect(404);
 await request(app).delete('/api/transactions/'+sell.id).set('Authorization','Bearer '+other).expect(404);
 await request(app).delete('/api/transactions/'+sell.id).set(auth).expect(204);
