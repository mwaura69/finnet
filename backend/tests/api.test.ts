 await request(app).put('/api/portfolios/'+p.id).set(auth).send({...input,name:'Updated Growth'}).expect(200);
 const base={instrument:'SCOM',type:'BUY',quantity:100,unitPrice:25,tradeDate:'2026-01-01'};
 const buy=(await request(app).post(`/api/portfolios/${p.id}/transactions`).set(auth).send(base).expect(201)).body.data;
