 assert.equal(db.prepare('SELECT COUNT(*) AS count FROM transactions').get()?.['count'],0);
 const missing=await request(app).get('/api/portfolios/missing').set(auth).expect(404);assert.equal(missing.body.error.code,'PORTFOLIO_NOT_FOUND');
